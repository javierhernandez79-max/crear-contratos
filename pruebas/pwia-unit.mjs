import { readFileSync, writeFileSync } from 'fs';
const R = '../js/';
const W = await import(R + 'plantilla-word.js');
const { moldeDocx, readZip } = await import(R + 'molde.js');
const { newContractFromTemplate } = await import(R + 'model.js');
const S = process.argv[2];
let fails = 0; const ok = (c, m) => { console.log(`${c ? 'OK  ' : 'FAIL'} ${m}`); if (!c) fails++; };
const bytes = new Uint8Array(readFileSync(S + '/pw/sin-marcas.docx'));
const prop = JSON.parse(readFileSync(S + '/pw/propuesta.json'));
const w = await W.leerWord(bytes);
ok(w.marcas === 0 && w.parrafos.length === 13 && w.parrafos[1].startsWith('QUE CELEBRAN INMUEBLES DEL CENTRO'), 'párrafos numerados, texto unido entre fragmentos');
const veces = W.contarCampos(W.numerarBlancos(w.parrafos), prop.campos);
ok(veces.join() === '3,2,2,1,1,1,1,1,1,1,0', 'conteo de apariciones: ' + veces);
const campos = prop.campos.filter((c, i) => veces[i]);
const marcado = await W.marcarWord(bytes, { campos, firmas: prop.firmas });
const w2 = await W.leerWord(marcado);
ok(w2.parrafos[1] === 'QUE CELEBRAN {{arrendador_nombre}}, REPRESENTADA POR {{arrendador_representante}}, A QUIEN SE LE DENOMINARÁ EL “ARRENDADOR”, Y {{arrendatario_nombre}}, EL “ARRENDATARIO”.', 'marcas en el párrafo partido: ' + w2.parrafos[1]);
ok(w2.parrafos[4] === 'II. El arrendatario señala como domicilio {{arrendatario_domicilio}}.', 'espacio en blanco → campo');
ok(w2.parrafos[8] === '_____________________', 'la línea de firma no se toca');
ok(w2.parrafos[10].endsWith('{{_ds_arrendador}}') && w2.parrafos[12].endsWith('{{_ds_arrendatario}}'), 'marcas de firma');
ok(!w2.parrafos.join(' ').includes('INMUEBLES DEL CENTRO'), 'el nombre no queda en ningún lado');
const etiquetas = Object.fromEntries(campos.map((c) => [c.clave, [c.etiqueta, c.tipo]]));
const partes = Object.fromEntries(prop.partes.map((p) => [p.prefijo, p]));
const { plantilla: t, avisos } = await W.plantillaDesdeWord(marcado, { nombre: 'Arrendamiento', categoria: 'comercial', archivo: 'x.docx', id: 'u-a', etiquetas, partes });
ok(t.vars.find((v) => v[0] === 'monto_renta')[1] === 'Renta mensual' && t.vars.find((v) => v[0] === 'monto_renta')[2] === 'money', 'etiqueta de la IA para dato propio');
ok(t.vars.find((v) => v[0] === 'arrendador_rfc')[1] === 'RFC (El “Arrendador”)', 'dato de parte con rol: ' + t.vars.find((v) => v[0] === 'arrendador_rfc')[1]);
ok(t.signers.map((s) => s.role).join('|') === 'El “Arrendador”|El “Arrendatario”', 'firmantes con el rol del contrato');
ok(!avisos.length, 'sin avisos: ' + avisos);
// Llenado final: los datos nuevos donde estaban los del caso y el sello en la línea de firma
const c = newContractFromTemplate(t);
Object.assign(c.variables, { arrendador_nombre: 'OTRA SA', arrendador_representante: 'PEPE', arrendatario_nombre: 'MARÍA', arrendador_domicilio: 'Calle 2', arrendador_rfc: 'XXX', arrendatario_domicilio: 'Calle 3', monto_renta: '20000', fecha_inicio: '2027-01-01', ciudad_firma: 'Puebla', fecha_firma: '2026-12-01' });
const out = await readZip(new Uint8Array(await (await moldeDocx(c, t.molde, { anchors: { arrendador: 'ANC1', arrendatario: 'ANC2' } })).arrayBuffer()));
const xml = new TextDecoder().decode(out.find((f) => f.name === 'word/document.xml').data);
ok(xml.includes('OTRA SA') && xml.includes('VEINTE MIL PESOS') && xml.includes('Puebla') && !/\{\{/.test(xml), 'Word final llenado sin llaves');
ok(/ANC1<\/w:t><\/w:r><w:r><w:t xml:space="preserve">_____/.test(xml), 'sello del arrendador al inicio de su línea de firma');
writeFileSync(S + '/pw/marcado-final.docx', Buffer.from(await (await moldeDocx(c, t.molde, {})).arrayBuffer()));
console.log(fails ? `${fails} FALLAS` : 'TODO OK');
