import { chromium } from 'playwright';
import { createMockDropbox } from './mockdbx.mjs';
const APP = 'http://localhost:5173/';
const mock = createMockDropbox();
mock.put('/Contratos App/LEEME.txt', Buffer.from('x'));
const b = await chromium.launch({ executablePath: process.env.CHROMIUM || undefined });
const errors = []; const ok = (c, m) => { console.log(`${c ? 'OK  ' : 'FAIL'} ${m}`); if (!c) errors.push(m); };
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 }, acceptDownloads: true });
await mock.attach(ctx, { id: 'a', name: 'Usuario Uno', email: 'a@example.com' });
const pg = await ctx.newPage(); pg.on('pageerror', (e) => errors.push(e.message));
await pg.goto(APP + '#/ajustes'); await pg.fill('#dbx-key', 'k'); await pg.fill('#dbx-folder', '/Contratos App');
await pg.click('[data-dbx=connect]'); await pg.waitForSelector('[data-dbx=sync]');
const id = await pg.evaluate(async () => {
  const m = await import('./js/model.js');
  const tpl = { id: 'u-t', name: 'Prestación', titulo: 'Contrato de Prestación de Servicios', category: 'servicios', vars: [['x', 'X', 'text'], ['fecha_firma', 'F', 'date']], sections: [{ title: 'O', body: 'T {{x}}.' }],
    signers: [{ role: 'P', name: 'P', bind: { prefix: 'prestador' } }, { role: 'C', name: 'C', bind: { prefix: 'cliente' } }] };
  const r = indexedDB.open('crear-contratos'); const d = await new Promise((x) => { r.onsuccess = () => x(r.result); });
  const put = (st, v) => new Promise((x) => { const tx = d.transaction(st, 'readwrite'); tx.objectStore(st).put(v); tx.oncomplete = x; });
  await put('templates', { ...tpl, custom: true });
  const base = { activa: true, rfc: '', apoderados: [], accionistas: [], createdAt: 1, updatedAt: 1 };
  await put('parties', { ...base, id: 'g1', kind: 'pm', propia: true, nombre: 'EPSILON SA DE CV' });
  await put('parties', { ...base, id: 'k1', kind: 'pm', propia: false, nombre: 'ALFADOC S.A. DE C.V.' });
  const c = m.newContractFromTemplate(tpl); c.variables = { x: 'u', fecha_firma: '2099-10-14' }; c.status = 'aprobado'; c.aprobado = { by: 'x', date: 1 };
  c.signers[0].party = { id: 'g1' }; c.signers[1].party = { id: 'k1' }; c.documentos = [];
  await put('contracts', c); return c.id;
});
await pg.goto(APP + '#/'); await pg.reload(); await pg.waitForSelector('.contract-list .ll-row[data-id]');
const head = await pg.textContent('.contract-list .ll-head'); ok(/Tipo de documento\s*Fecha\s*Estado/.test(head), 'columna Fecha: ' + head);
const fila = await pg.textContent(`.ll-row[data-id="${id}"]`); ok(/14 oct 2099/.test(fila), 'fecha en la fila: ' + fila.replace(/\s+/g, ' ').slice(0, 160));
await pg.setViewportSize({ width: 390, height: 800 }); await pg.waitForTimeout(300);
const vis = await pg.evaluate((i) => [...document.querySelectorAll(`.ll-row[data-id="${i}"] > span`)].map((s) => getComputedStyle(s).display !== 'none'), id);
ok(vis.join() === 'true,false,false,false,true,false,false,false,true', 'móvil: cliente, estado y acciones ' + vis.join());
await pg.setViewportSize({ width: 1280, height: 900 });
await pg.evaluate((i) => { location.hash = `#/c/${i}/documento`; }, id);
await pg.waitForSelector('#app [data-wf=approve]');
const t = await pg.textContent('#app [data-wf=approve]'); ok(/Volver a guardar/.test(t), 'botón para regenerar: ' + t);
await Promise.all([pg.waitForEvent('download'), pg.click('#app [data-wf=approve]').then(() => pg.click('dialog[open] button[value=ok]'))]); await pg.waitForTimeout(1500);
const files = [...mock.files.values()].map((f) => f.path);
ok(files.some((p) => p.endsWith('ContratoDePrestacionDeServicios-Alfadoc-Epsilon-2099-10-14-APROBADO.docx')), 'Word aprobado regenerado en Dropbox');
ok(await pg.locator('#app [data-wf=approve]').count() === 0, 'el botón desaparece cuando ya hay Word aprobado');
ok(!errors.length, 'sin errores: ' + errors.join(' | '));
await b.close(); process.exit(errors.length ? 1 : 0);
