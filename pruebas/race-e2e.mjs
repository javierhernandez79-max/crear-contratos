import { chromium } from 'playwright';
import { createMockDropbox } from './mockdbx.mjs';
const APP = 'http://localhost:5173/';
const mock = createMockDropbox();
mock.put('/Contratos App/LEEME.txt', Buffer.from('x'));
mock.opts.only = '/datos-app/contratos/';
const b = await chromium.launch({ executablePath: process.env.CHROMIUM || undefined });
const errors = []; const ok = (c, m) => { console.log(`${c ? 'OK  ' : 'FAIL'} ${m}`); if (!c) errors.push(m); };
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
await mock.attach(ctx, { id: 'a', name: 'Usuario Uno', email: 'a@example.com' });
const pg = await ctx.newPage();
pg.on('pageerror', (e) => errors.push(e.message));
await pg.goto(APP + '#/ajustes'); await pg.waitForSelector('#dbx-key');
await pg.fill('#dbx-key', 'appkey123'); await pg.fill('#dbx-folder', '/Contratos App');
await pg.click('[data-dbx=connect]'); await pg.waitForSelector('[data-dbx=sync]', { timeout: 15000 });
const sync = async () => { await pg.click('#sync-pill'); await pg.waitForFunction(() => !document.querySelector('#sync-pill').classList.contains('busy'), null, { timeout: 20000 }); await pg.waitForTimeout(300); };
await sync();
await pg.goto(APP + '#/plantillas'); await pg.waitForSelector('.tpl-list .ll-row[data-id]');
await pg.locator('.tpl-list .ll-row[data-id]').first().locator('[data-act=view]').click();
await pg.waitForSelector('dialog.modal button[value=use]'); await pg.click('dialog.modal button[value=use]');
await pg.waitForSelector('#doc-title');
await pg.fill('#doc-title', 'T1'); await pg.waitForTimeout(800);
await sync();
const remoteTitle = () => { for (const f of mock.files.values()) if (f.path.includes('/datos-app/contratos/')) return JSON.parse(f.data.toString()).title; };
ok(remoteTitle() === 'T1', 'T1 subido');
// Edición mientras la subida está en curso
mock.opts.delay = 2500;
await pg.click('#sync-pill');
await pg.waitForTimeout(700);
await pg.fill('#doc-title', 'T2'); await pg.waitForTimeout(800);
await pg.waitForFunction(() => !document.querySelector('#sync-pill').classList.contains('busy'), null, { timeout: 20000 });
mock.opts.delay = 0;
ok(await pg.inputValue('#doc-title') === 'T2', 'el editor conserva T2 tras la sincronización');
await pg.waitForTimeout(300); await sync();
ok(remoteTitle() === 'T2', 'la edición hecha durante la sincronización llega a Dropbox: ' + remoteTitle());
// Borrado mientras se sube
await pg.fill('#doc-title', 'T3'); await pg.waitForTimeout(800);
mock.opts.delay = 2500;
await pg.click('#sync-pill'); await pg.waitForTimeout(700);
const id = await pg.evaluate(() => location.hash.split('/')[2]);
await pg.evaluate(async (id) => { const m = await import('/js/sync.js'); const db = await import('/js/db.js'); await db.remove('contracts', id); await m.markDeleted('contracts', id); }, id);
await pg.waitForFunction(() => !document.querySelector('#sync-pill').classList.contains('busy'), null, { timeout: 20000 });
mock.opts.delay = 0; await pg.goto(APP + '#/'); await pg.waitForTimeout(300); await sync(); await sync();
ok(remoteTitle() === undefined, 'lo borrado durante la subida no vuelve y se borra de Dropbox');
ok(!(await pg.evaluate(async (id) => !!(await (await import('/js/db.js')).get('contracts', id)), id)), 'no reaparece en el equipo');
console.log(errors.length ? 'ERRORES: ' + errors.join(' | ') : 'TODO OK'); await b.close();
