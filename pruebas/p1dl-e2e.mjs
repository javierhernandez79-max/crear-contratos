import { chromium } from 'playwright'; import fs from 'fs'; import { createMockDropbox } from './mockdbx.mjs';
const S = process.argv[2]; const APP = 'http://localhost:5173/';
const mock = createMockDropbox(); mock.put('/Contratos App/LEEME.txt', Buffer.from('x'));
const p1 = fs.readFileSync(S + '/p1/entrega/P1 - plantilla.xlsx'); mock.put('/Contratos App/PLANTILLAS MARCO/P1 - plantilla.xlsx', p1);
const errors = []; const ok = (c, m) => { console.log(`${c ? 'OK  ' : 'FAIL'} ${m}`); if (!c) errors.push(m); };
const b = await chromium.launch({ executablePath: process.env.CHROMIUM || undefined });
const ctx = await b.newContext({ acceptDownloads: true }); await mock.attach(ctx, { id: 'a', name: 'A', email: 'a@x.com' });
const pg = await ctx.newPage(); pg.on('pageerror', (e) => errors.push(e.message));
await pg.goto(APP + '#/ajustes'); await pg.waitForSelector('#dbx-key');
await pg.fill('#dbx-key', 'appkey123'); await pg.fill('#dbx-folder', '/Contratos App'); await pg.click('[data-dbx=connect]');
await pg.waitForSelector('[data-dbx=sync]', { timeout: 15000 });
await pg.goto(APP + '#/lotes'); await pg.waitForSelector('#p1-blank');
let [d] = await Promise.all([pg.waitForEvent('download'), pg.click('#p1-blank')]);
await d.saveAs(S + '/p1-dl.xlsx');
ok(Buffer.compare(fs.readFileSync(S + '/p1-dl.xlsx'), p1) === 0 && d.suggestedFilename() === 'P1 - plantilla.xlsx', 'descarga el P1 de Dropbox tal cual');
mock.files.delete('/contratos app/plantillas marco/p1 - plantilla.xlsx');
[d] = await Promise.all([pg.waitForEvent('download'), pg.click('#p1-blank')]);
ok(d.suggestedFilename() === 'P1 - columnas.xlsx', 'sin archivo en Dropbox descarga el de encabezados');
console.log('errors:', errors); await b.close(); process.exit(errors.length ? 1 : 0);
