import { generateKeyPairSync, createSign, webcrypto } from 'crypto';
const { onRequestPost } = await import('../functions/api/docusign/convertir.js');
const errors = []; const ok = (c, m) => { console.log(`${c ? 'OK  ' : 'FAIL'} ${m}`); if (!c) errors.push(m); };
const b64u = (b) => Buffer.from(b).toString('base64url');
// Llave de Access para firmar el token del usuario
const acc = generateKeyPairSync('rsa', { modulusLength: 2048 });
const jwk = { ...acc.publicKey.export({ format: 'jwk' }), kid: 'k1' };
const now = Math.floor(Date.now() / 1000);
const head = b64u(JSON.stringify({ alg: 'RS256', kid: 'k1' })); const pay = b64u(JSON.stringify({ email: 'Ana@x.com', iss: 'https://t.cloudflareaccess.com', exp: now + 600 }));
const sig = createSign('RSA-SHA256').update(`${head}.${pay}`).sign(acc.privateKey);
const jwt = `${head}.${pay}.${b64u(sig)}`;
const ds = generateKeyPairSync('rsa', { modulusLength: 2048 });
const env = { ACCESS_TEAM: 't.cloudflareaccess.com', DOCUSIGN_INTEGRATION_KEY: '11111111-1111-1111-1111-111111111111', DOCUSIGN_USER_ID: '22222222-2222-2222-2222-222222222222', DOCUSIGN_PRIVATE_KEY: ds.privateKey.export({ type: 'pkcs8', format: 'pem' }) };
const llamadas = [];
globalThis.fetch = async (url, o = {}) => {
  llamadas.push({ url: String(url), method: o.method || 'GET', body: o.body, headers: o.headers });
  const j = (x, s = 200) => new Response(JSON.stringify(x), { status: s, headers: { 'Content-Type': 'application/json' } });
  if (String(url).endsWith('/cdn-cgi/access/certs')) return j({ keys: [jwk] });
  if (String(url).endsWith('/oauth/token')) return j({ access_token: 'tok', expires_in: 3600 });
  if (String(url).endsWith('/oauth/userinfo')) return j({ name: 'X', email: 'x@x', accounts: [{ account_id: 'acc1', account_name: 'Desp', base_uri: 'https://demo.docusign.net', is_default: true }] });
  if (String(url).endsWith('/accounts/acc1/envelopes') && o.method === 'POST') return j({ envelopeId: 'env-123' }, 201);
  if (String(url).endsWith('/envelopes/env-123/documents/1')) return new Response('%PDF-1.7 convertido', { headers: { 'Content-Type': 'application/pdf' } });
  if (String(url).endsWith('/folders/recyclebin')) return j({});
  return j({ message: 'no esperado ' + url }, 404);
};
const req = (body, extra = {}) => new Request('https://app/api/docusign/convertir', { method: 'POST', headers: { 'Cf-Access-Jwt-Assertion': jwt, 'X-Nombre': encodeURIComponent('Contrato-APROBADO.docx'), ...extra }, body });
let r = await onRequestPost({ request: req(new Uint8Array([80, 75, 3, 4, 1, 2])), env });
ok(r.status === 200 && r.headers.get('Content-Type') === 'application/pdf', 'responde PDF: ' + r.status);
ok((await r.text()).startsWith('%PDF'), 'contenido del PDF de DocuSign');
const crear = llamadas.find((x) => x.url.endsWith('/envelopes') && x.method === 'POST');
const cuerpo = JSON.parse(crear.body);
ok(cuerpo.status === 'created' && !cuerpo.recipients && cuerpo.documents[0].fileExtension === 'docx' && cuerpo.documents[0].documentBase64 === Buffer.from([80, 75, 3, 4, 1, 2]).toString('base64'), 'sobre en borrador, sin destinatarios, con el Word');
const doc = llamadas.find((x) => x.url.endsWith('/documents/1'));
ok(doc.headers.Accept === 'application/pdf', 'pide el documento como PDF');
const papelera = llamadas.find((x) => x.url.endsWith('/folders/recyclebin'));
ok(papelera && papelera.method === 'PUT' && JSON.parse(papelera.body).envelopeIds[0] === 'env-123', 'borrador a la papelera');
r = await onRequestPost({ request: new Request('https://app/x', { method: 'POST', body: 'x' }), env });
ok(r.status === 401, 'sin sesión: 401');
r = await onRequestPost({ request: req(new Uint8Array(0)), env });
ok(r.status === 400, 'Word vacío: 400');
r = await onRequestPost({ request: req(new Uint8Array([1])), env: { ...env, DOCUSIGN_PRIVATE_KEY: '' } });
ok(r.status === 503, 'sin configuración: 503');
process.exit(errors.length ? 1 : 0);
