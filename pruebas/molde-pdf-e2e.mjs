import { chromium } from 'playwright'; import fs from 'fs';
import { createMockDropbox } from './mockdbx.mjs';
const APP = 'http://localhost:5173/';
const errors = []; const ok = (c, m) => { console.log(`${c ? 'OK  ' : 'FAIL'} ${m}`); if (!c) errors.push(m); };
const f2 = JSON.parse(fs.readFileSync('../fmt/formatos-cps.json')).templates.find((t) => t.formato === 'F2');
const mock = createMockDropbox();
mock.put('/Contratos App/LEEME.txt', Buffer.from('x'));
const b = await chromium.launch({ executablePath: process.env.CHROMIUM || undefined });
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 }, acceptDownloads: true });
await mock.attach(ctx, { id: 'a', name: 'Usuario Uno', email: 'a@example.com' });
await ctx.route('**/api/docusign/estado', (r) => r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ configurada: true, conectada: true, env: 'demo', cuenta: { id: 'acc1', name: 'C' }, remitente: { name: 'R', email: 'r@x' }, remitenteId: '2', admin: true }) }));
let falla = true; const conversiones = [];
await ctx.route('**/api/docusign/convertir', async (r) => {
  conversiones.push({ nombre: decodeURIComponent(r.request().headers()['x-nombre']), cuerpo: r.request().postDataBuffer() });
  if (falla) return r.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ message: 'DocuSign no disponible' }) });
  return r.fulfill({ status: 200, contentType: 'application/pdf', body: Buffer.from('%PDF-1.7 convertido por DocuSign') });
});
const pg = await ctx.newPage(); pg.on('pageerror', (e) => errors.push(e.message));
const files = () => [...mock.files.values()].map((f) => f.path);
await pg.goto(APP + '#/ajustes'); await pg.fill('#dbx-key', 'k'); await pg.fill('#dbx-folder', '/Contratos App');
await pg.click('[data-dbx=connect]'); await pg.waitForSelector('[data-dbx=sync]');
const id = await pg.evaluate(async (t) => {
  const m = await import('./js/model.js');
  const c = m.newContractFromTemplate(t);
  for (const d of c.varDefs) c.variables[d.key] = d.key === 'fecha_firma' ? '2099-01-15' : 'DATO ' + d.key;
  c.signers[0].party = { id: 'g1', apoderadoId: null, prefix: 'prestador' }; c.signers[1].party = { id: 'k1', apoderadoId: null, prefix: 'cliente' };
  const r = indexedDB.open('crear-contratos'); const d = await new Promise((x) => { r.onsuccess = () => x(r.result); });
  const put = (st, v) => new Promise((x) => { const tx = d.transaction(st, 'readwrite'); tx.objectStore(st).put(v); tx.oncomplete = x; });
  const base = { activa: true, rfc: '', correo: '', apoderados: [], accionistas: [] };
  await put('parties', { ...base, id: 'g1', kind: 'pm', propia: true, nombre: 'GRUPO EJEMPLO, S.A. DE C.V.' });
  await put('parties', { ...base, id: 'k1', kind: 'pm', propia: false, nombre: 'ALFADOC S.A. DE C.V.' });
  await put('templates', t); await put('contracts', c); return c.id;
}, f2);
await pg.goto(APP + '#/'); await pg.reload(); await pg.waitForSelector('#app');
await pg.evaluate((i) => { location.hash = `#/c/${i}/documento`; }, id);
await pg.waitForSelector('[data-wf=revision]');
await Promise.all([pg.waitForEvent('download'), pg.click('[data-wf=revision]')]); await pg.waitForSelector('[data-wf=approve]');
const rev = files().find((p) => p.endsWith('-REVISION.docx'));
ok(rev && mock.files.get(rev.toLowerCase()).data.subarray(0, 2).toString() === 'PK', 'Word de revisión del formato en Dropbox: ' + rev?.split('/').pop());
// Aprobar con DocuSign caído: se aprueba con el Word y queda el botón para el PDF
await Promise.all([pg.waitForEvent('download'), pg.click('[data-wf=approve]').then(() => pg.click('dialog.modal button[value=ok]'))]);
await pg.waitForSelector('[data-wf=pdf-ds]');
ok(files().some((p) => p.endsWith('-APROBADO.docx')) && !files().some((p) => p.endsWith('-APROBADO.pdf')), 'DocuSign falla: aprobado solo con Word');
ok(!files().some((p) => p.endsWith('-REVISION.docx')), 'Word de revisión quitado al aprobar');
ok(conversiones.length === 1 && conversiones[0].nombre.endsWith('-APROBADO.docx') && conversiones[0].cuerpo.subarray(0, 2).toString() === 'PK', 'mandó el Word aprobado a convertir');
falla = false;
await pg.click('[data-wf=pdf-ds]'); await pg.waitForSelector('[data-wf=ds-send]'); await pg.waitForTimeout(800);
const pdf = files().find((p) => p.endsWith('-APROBADO.pdf'));
ok(pdf && mock.files.get(pdf.toLowerCase()).data.toString().includes('convertido por DocuSign'), 'PDF aprobado convertido por DocuSign en Dropbox');
ok(await pg.locator('[data-wf=pdf-ds]').count() === 0, 'el botón desaparece con el PDF');
// Reaprobar (ya con DocuSign): PDF directo al aprobar
await pg.evaluate(async (i) => { const r = indexedDB.open('crear-contratos'); const d = await new Promise((x) => { r.onsuccess = () => x(r.result); });
  const c = await new Promise((x) => { const q = d.transaction('contracts').objectStore('contracts').get(i); q.onsuccess = () => x(q.result); }); c.status = 'revision';
  await new Promise((x) => { const tx = d.transaction('contracts', 'readwrite'); tx.objectStore('contracts').put(c); tx.oncomplete = x; }); }, id);
await pg.reload(); await pg.waitForSelector('#app'); await pg.evaluate((i) => { location.hash = `#/c/${i}/documento`; }, id); await pg.waitForSelector('[data-wf=approve]');
const n0 = conversiones.length;
await Promise.all([pg.waitForEvent('download'), pg.click('[data-wf=approve]').then(() => pg.click('dialog.modal button[value=ok]'))]);
await pg.waitForSelector('[data-wf=ds-send]'); await pg.waitForTimeout(800);
ok(conversiones.length === n0 + 1 && files().filter((p) => p.endsWith('-APROBADO.pdf')).length === 1, 'al aprobar con DocuSign disponible sale el PDF directo (uno solo)');
ok(!errors.length, 'sin errores: ' + errors.join(' | '));
await b.close(); process.exit(errors.length ? 1 : 0);
