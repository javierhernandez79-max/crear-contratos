import { chromium } from 'playwright'; import fs from 'fs';
const S = process.argv[2]; const APP = 'http://localhost:5173/';
const errors = []; const ok = (c, m) => { console.log(`${c ? 'OK  ' : 'FAIL'} ${m}`); if (!c) errors.push(m); };
const tpl = JSON.parse(fs.readFileSync('../marco/out/u-marco-trabajo-indeterminado.json'));
const b = await chromium.launch({ executablePath: process.env.CHROMIUM || undefined });
const pg = await b.newPage({ viewport: { width: 1280, height: 900 } });
pg.on('pageerror', (e) => errors.push(e.message));
await pg.goto(APP + '#/lotes'); await pg.waitForSelector('#p1-blank');
await pg.evaluate(async (t) => {
  const r = indexedDB.open('crear-contratos'); const d = await new Promise((x) => { r.onsuccess = () => x(r.result); });
  const put = (store, v) => new Promise((x) => { const tx = d.transaction(store, 'readwrite'); tx.objectStore(store).put(v); tx.oncomplete = x; });
  await put('templates', t);
  await put('parties', { id: 'emp1', kind: 'pm', propia: true, activa: true, nombre: 'EMPRESA DEMO, S.A. DE C.V.', rfc: 'EDE010101AA1', domicilio: 'AV. DEMO 1, CDMX', apoderados: [{ id: 'apo1', nombre: 'MARIA APODERADA', cargo: 'Apoderado legal', vigente: true }], accionistas: [] });
}, tpl);
await pg.goto(APP + '#/lotes/nuevo'); await pg.reload(); await pg.waitForSelector('#l-tpl');
await pg.selectOption('#l-tpl', tpl.id); await pg.selectOption('#l-per', 'QUINCENAL'); await pg.selectOption('#l-emp', 'emp1'); await pg.fill('#l-cli', 'CLIENTE DEMO');
await pg.setInputFiles('#l-file', S + '/p1-bad.xlsx'); await pg.waitForSelector('.lt-row.bad');
ok((await pg.textContent('#l-create')).includes('(1 contrato)'), 'antes de corregir: 1 contrato');
await pg.click('.lt-row.bad [data-edit]'); await pg.waitForSelector('dialog.modal #p1-rfc');
ok(await pg.inputValue('#p1-rfc') === 'GORL8501019Z99', 'el formulario trae el RFC con error');
await pg.screenshot({ path: S + '/l7-corregir.png' });
await pg.fill('#p1-rfc', 'GORL850101AB2'); await pg.click('dialog.modal button[value=ok]');
await pg.waitForFunction(() => !document.querySelector('.lt-row.bad'));
ok(!(await pg.textContent('#l-create')).includes('('), 'después de corregir: sin errores');
ok((await pg.textContent('.lote-table')).includes('corregido aquí'), 'marca la fila corregida');
await pg.click('#l-create'); await pg.waitForSelector('#lote-approve');
ok(await pg.locator('.lt-row:not(.lt-head)').count() === 2 && !(await pg.locator('#lote-err-word').count()), 'lote con 2 contratos y sin excluidos');
ok((await pg.textContent('.history')).includes('corregida(s) en la plataforma'), 'historial registra la corrección');
await pg.click('#lote-approve'); await pg.click('dialog.modal button[value=ok]'); await pg.waitForSelector('#lote-zip');
ok((await pg.textContent('#lote-p1')).includes('P1 corregido'), 'botón de P1 corregido en el lote');
const [z] = await Promise.all([pg.waitForEvent('download'), pg.click('#lote-zip')]);
await z.saveAs(S + '/lote-ed.zip');
const { execSync } = await import('child_process');
const list = execSync(`unzip -l ${S}/lote-ed.zip`).toString();
ok(list.includes('00 - P1 - p1-bad (corregido).xlsx'), 'el zip incluye el P1 corregido');
execSync(`cd ${S} && rm -rf lze && mkdir lze && cd lze && unzip -q ../lote-ed.zip`);
const ExcelJS = (await import('exceljs')).default; const wb = new ExcelJS.Workbook();
await wb.xlsx.readFile(S + '/lze/00 - P1 - p1-bad (corregido).xlsx');
const ws = wb.worksheets[0]; let rfcCol = 0; ws.getRow(1).eachCell((c, i) => { if (c.value === 'RFC con Homoclave') rfcCol = i; });
ok(ws.getRow(3).getCell(rfcCol).value === 'GORL850101AB2' && ws.getRow(3).getCell(rfcCol).fill?.fgColor?.argb === 'FFFFF2CC', 'P1 con el RFC corregido y resaltado');
ok(ws.getRow(2).getCell(rfcCol).value === 'PELA900101AB1', 'las demás filas quedan igual');
console.log('errors:', errors); await b.close(); process.exit(errors.length ? 1 : 0);
