import { chromium } from 'playwright';
import { habilesEntre } from '../js/habiles.js';
const S = process.argv[2] || 'shots'; const APP = 'http://localhost:5173/';
const errors = []; const ok = (c, m) => { console.log(`${c ? 'OK  ' : 'FAIL'} ${m}`); if (!c) errors.push(m); };
const b = await chromium.launch({ executablePath: process.env.CHROMIUM || undefined });
const pg = await b.newPage({ viewport: { width: 1280, height: 900 } });
pg.on('pageerror', (e) => errors.push(e.message));
pg.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errors.push('console: ' + m.text()); });
await pg.goto(APP + '#/'); await pg.waitForSelector('#app');
const DAY = 86400000;
const ids = await pg.evaluate(async (DAY) => {
  const m = await import('./js/model.js');
  const tpl = { id: 't', name: 'Servicios', titulo: 'SERVICIOS', vars: [['servicios', 'S', 'text']], sections: [{ title: 'OBJETO', body: '{{servicios}}' }],
    signers: [{ role: 'EL PRESTADOR', name: 'P', bind: { prefix: 'prestador' } }, { role: 'EL CLIENTE', name: 'CLIENTE DEMO', bind: { prefix: 'cliente' } }] };
  const mk = (title, ago, status, t = tpl) => { const c = m.newContractFromTemplate(t); c.title = title; c.createdAt = Date.now() - ago * DAY; c.status = status; return c; };
  const viejo = mk('SERV VIEJO', 40, 'aprobado');
  const nuevo = mk('SERV NUEVO', 2, 'borrador');
  const firmado = mk('SERV FIRMADO', 60, 'final');
  const otro = mk('NDA VIEJO', 60, 'aprobado', { ...tpl, vars: [['x', 'X', 'text']], sections: [{ title: 'A', body: '{{x}}' }], signers: [{ role: 'A', name: 'A' }] });
  const r = indexedDB.open('crear-contratos'); const d = await new Promise((x) => { r.onsuccess = () => x(r.result); });
  for (const c of [viejo, nuevo, firmado, otro]) await new Promise((x) => { const tx = d.transaction('contracts', 'readwrite'); tx.objectStore('contracts').put(c); tx.oncomplete = x; });
  return { viejo: viejo.id, nuevo: nuevo.id, createdViejo: viejo.createdAt };
}, DAY);
await pg.reload(); await pg.waitForSelector('.contract-list');
const iso = (ms) => { const d = new Date(ms); return new Date(d.getTime() - d.getTimezoneOffset() * 60000).toISOString().slice(0, 10); };
const esperado = habilesEntre(iso(ids.createdViejo), iso(Date.now()));
ok(await pg.locator('.banner >> text=con más de 15 días hábiles sin firma').count() === 1, 'banner en inicio');
ok(await pg.textContent('#venc-badge') === '1', 'contador del menú = 1');
const rowViejo = await pg.textContent(`.contract-list .ll-row[data-id="${ids.viejo}"]`);
ok(rowViejo.includes(`${esperado} días háb. sin firma`), `lista: ${esperado} días hábiles`);
ok((await pg.textContent(`.contract-list .ll-row[data-id="${ids.nuevo}"]`)).includes('háb. sin firma'), 'nuevo también muestra contador');
ok(!(await pg.locator('.contract-list .ll-row', { hasText: 'SERV FIRMADO' }).textContent()).includes('háb.'), 'firmado sin contador');
ok(!(await pg.locator('.contract-list .ll-row', { hasText: 'NDA VIEJO' }).textContent()).includes('háb.'), 'no servicios sin contador');
await pg.screenshot({ path: S + '/f1-inicio.png', fullPage: true });
await pg.evaluate(() => { location.hash = '#/vencimientos'; }); await pg.waitForSelector('.firma-list');
ok(await pg.locator('.firma-list .ll-row[data-cid]').count() === 1, 'vencimientos: 1 atrasado');
ok((await pg.textContent('.firma-list')).includes('CLIENTE DEMO'), 'muestra cliente');
await pg.screenshot({ path: S + '/f2-venc.png', fullPage: true });
await pg.click('[data-ff=plazo]');
ok(await pg.locator('.firma-list .ll-row[data-cid]').count() === 1, 'en plazo: 1 (el nuevo)');
await pg.click('[data-ff=atrasados]');
await pg.click('.firma-list [data-act=discard]');
await pg.fill('dialog.modal input[name=nota]', 'cliente canceló');
await pg.click('dialog.modal button[value=ok]');
await pg.waitForTimeout(300);
ok(await pg.locator('.firma-list .ll-row[data-cid]').count() === 0, 'descartado sale de atrasados');
ok((await pg.textContent('#venc-badge')) === '' , 'contador en 0');
await pg.click('[data-ff=descartados]');
await pg.click('.firma-list [data-act=undo]');
await pg.waitForTimeout(300);
ok((await pg.textContent('#venc-badge')) === '1', 'reactivado');
await pg.evaluate((id) => { location.hash = `#/c/${id}/firmas`; }, ids.viejo); await pg.waitForSelector('#editor-head');
ok((await pg.textContent('#editor-head')).includes('háb. sin firma'), 'encabezado del contrato');
// Ya no hay botón "Marcar firmado": el contrato queda firmado con DocuSign o "Firmado en papel"; aquí se simula el estado final
await pg.evaluate(async (id) => { const r = indexedDB.open('crear-contratos'); const d = await new Promise((x) => { r.onsuccess = () => x(r.result); });
  const c = await new Promise((x) => { const q = d.transaction('contracts').objectStore('contracts').get(id); q.onsuccess = () => x(q.result); });
  c.status = 'final'; await new Promise((x) => { const tx = d.transaction('contracts', 'readwrite'); tx.objectStore('contracts').put(c); tx.oncomplete = x; }); }, ids.viejo);
await pg.reload(); await pg.waitForSelector('#editor-head'); await pg.waitForTimeout(400);
ok(!(await pg.textContent('#editor-head')).includes('háb. sin firma'), 'al marcar firmado desaparece');
ok((await pg.textContent('#venc-badge')) === '', 'contador en 0 tras firmar');
await pg.setViewportSize({ width: 390, height: 800 });
await pg.evaluate(() => { location.hash = '#/vencimientos'; }); await pg.waitForSelector('.firma-list, .empty-inline');
ok(await pg.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'móvil sin scroll horizontal');
console.log(errors.length ? 'ERRORES: ' + errors.join(' | ') : 'TODO OK'); await b.close();
